import AppKit
import UniformTypeIdentifiers
#if canImport(StampedeCore)
import StampedeCore
#endif

@MainActor final class SystemClipboardClient: ClipboardClient {
    private let pasteboard: NSPasteboard
    init(pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }
    var revision: Int { pasteboard.changeCount }
    var accessState: ClipboardAccessState {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow: return .allowed
            case .default: return .notDetermined
            case .ask: return .ask
            case .alwaysDeny: return .denied
            @unknown default: return .unknown
            }
        }
        return .allowed
    }
    var canReadInBackground: Bool { accessState == .allowed }
    func read() -> ClipboardRead {
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny { return .unavailable }
        guard let items = pasteboard.pasteboardItems else { return .unavailable }
        guard !items.isEmpty else { return .excluded }
        guard items.count == 1, let item = items.first else { return .excluded }
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !item.types.contains(where: { excluded.contains($0.rawValue) }) else { return .excluded }
        guard !item.types.contains(where: { type in
            guard let ut = UTType(type.rawValue) else { return false }
            return ut.conforms(to: .image) || ut.conforms(to: .fileURL)
        }) else { return .excluded }
        guard item.types.contains(.string) else { return .excluded }
        guard let text = item.string(forType: .string) else { return .unavailable }
        return .text(text)
    }
    func clear() -> Int { pasteboard.clearContents() }
    func write(_ text: String) -> Bool {
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return false }
        // clearContents resets local-only options; ordinary writes remain eligible for Universal Clipboard.
        pasteboard.clearContents()
        return pasteboard.writeObjects([item])
    }
}
